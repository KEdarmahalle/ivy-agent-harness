"""Autonomous Jira Automation Background Worker.

Provides:
- User story breakdown into technical architecture, invariants, and acceptance criteria.
- Autonomous Jira comment posting.
"""

from __future__ import annotations

import base64
import json
import os
import urllib.request
from typing import Any

from harness.sdk import AgentHarness


def post_jira_comment(
    issue_key: str,
    comment: str,
    jira_url: str | None = None,
    jira_email: str | None = None,
    jira_token: str | None = None,
) -> dict[str, Any]:
    """Post a comment to an Atlassian Jira issue."""
    base_url = jira_url or os.environ.get("JIRA_URL") or os.environ.get("JIRA_BASE_URL")
    email = jira_email or os.environ.get("JIRA_EMAIL")
    token = jira_token or os.environ.get("JIRA_API_TOKEN")

    if not base_url or not email or not token:
        return {
            "status": "dry_run",
            "issue_key": issue_key,
            "comment_len": len(comment),
        }

    url = f"{base_url.rstrip('/')}/rest/api/3/issue/{issue_key}/comment"
    auth_header = base64.b64encode(f"{email}:{token}".encode()).decode("utf-8")

    payload = {
        "body": {
            "type": "doc",
            "version": 1,
            "content": [
                {
                    "type": "paragraph",
                    "content": [{"type": "text", "text": comment}],
                }
            ],
        }
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Basic {auth_header}",
            "Accept": "application/json",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=10.0) as resp:
            res_data = json.loads(resp.read().decode("utf-8"))
            return {"status": "posted", "comment_id": res_data.get("id"), "issue_key": issue_key}
    except Exception as exc:  # noqa: BLE001 - convert integration failures to worker results
        return {"status": "error", "error": str(exc), "issue_key": issue_key}


async def on_jira_issue_created(
    issue_key: str,
    summary: str,
    description: str,
    jira_url: str | None = None,
    jira_email: str | None = None,
    jira_token: str | None = None,
    post_comment: bool = True,
) -> dict[str, Any]:
    """Autonomous Jira Story Breakdown: produces technical design and acceptance tests."""
    harness = AgentHarness.from_project(workspace_root=".")
    prompt = (
        f"Jira Issue [{issue_key}]: {summary}\n\n"
        f"Requirements:\n{description}\n\n"
        "Generate a structured engineering breakdown including:\n"
        "1. Architectural Invariants\n"
        "2. Component Changes Required\n"
        "3. Automated Acceptance Test Criteria"
    )
    result = await harness.arun(prompt)

    comment_text = (
        f"⚡ Ivy Autonomous Story Breakdown ({issue_key})\n\n"
        f"{result.final_output}\n\n"
        "---\n*Generated by Ivy Autonomous Harness.*"
    )

    dispatch_res = {}
    if post_comment:
        dispatch_res = post_jira_comment(
            issue_key=issue_key,
            comment=comment_text,
            jira_url=jira_url,
            jira_email=jira_email,
            jira_token=jira_token,
        )

    return {
        "status": "completed",
        "issue_key": issue_key,
        "breakdown": comment_text,
        "jira_dispatch": dispatch_res,
    }
